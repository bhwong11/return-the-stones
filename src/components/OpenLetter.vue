    <br/>
    <h2 class="title">
      <b>An Open Letter to the Museum of the Bible</b>
    </h2>
    <br />
    <p>
      To the leadership of the Museum of the Bible and to churches, faith communities, museums, universities, governments, cultural institutions, and people of conscience: <b>We write this open letter as a call for moral accountability and as the beginning of a campaign to defend the integrity of Christian heritage in the Holy Land.</b>
    </p>
    <br />
    <p>
      The Museum of the Bible presents itself as an institution dedicated to preserving and sharing the history of Scripture and the communities shaped by it. A museum with this mission has a responsibility to ask, “Whose voices are being heard? Whose history is being preserved? What happens when sacred heritage is severed from the communities that have lived and preserved it across generations?”
    </p>
    <br />
    <p>
      Instead of addressing these issues with integrity, the Museum partners with the Israel Antiquities Authority (IAA), which supplies the Museum with artifacts the IAA has gained through expelling Palestinians and occupying their land. 
    </p>
    <br />
    <p>
      For this reason, we call upon the Museum of the Bible to end its partnership with the IAA which operates to erase the memory of long-established Palestinian presence in the land. The IAA repeatedly declares areas “antiquity sites” and works with the military to expel Palestinians living there. With Palestinians expelled, Israeli settlers and the state take the land, erasing Palestinian history and life from that area. Museum exhibits gained through the expulsion of communities are unjust, especially for a Museum that claims to be faithful to scripture. 
    </p>
    <br />
    <p>
      The Megiddo Mosaic displayed at the Museum illustrates this pattern of dispossession and acquisition. It comes from one of the earliest known Christian spaces, dating to approximately 230 CE. It is well preserved with an inscription dedicating that space "to the God Jesus Christ." This mosaic is an extraordinary testimony to the earliest generations of the Christian faith.
    </p>
    <br />
    <p>
      But there is more to the story of how this Mosaic came to be discovered and how it has ended up at the Museum of the Bible. The Mosaic was discovered at the site of ancient Legio, in what was once the village of Lajjun near Megiddo. In 1948, the Israeli Golani Brigade occupied the village of Lajjun and displaced much of the Palestinian community that had lived there for generations. Megiddo Prison was established at the site and, by the late 1980s, Israel used it to incarcerate Palestinians, many of whom were held in ‘administrative detention’ without trial.
    </p>
    <br />
    <p>
      In 2005, Israel set out to enlarge the Megiddo Prison and found the Mosaic in the process. Through its partnership with the IAA, the Museum of the Bible received it in 2024. The Museum now has the Mosaic, removed from its original context, while the prison above it remains in operation as a site with documented abuse drawing widespread international condemnation for torture, deaths in custody, and other human rights abuses.
    </p>
    <br />
    <p>
      The Museum of the Bible must ask whether displaying the Megiddo Mosaic while separating it from its land, history, and heritage truly honors its Christian heritage. The Museum must also decide if it will continue to partner with the IAA, which uses antiquities as a way of seizing land from Palestinians, including Palestinian Christians.
    </p>
    <br />
    <p>
      By partnering with the IAA, the Museum of the Bible appears to condone its methods, which use archaeology as a quest for material evidence of ancient Israel while simultaneously erasing and marginalizing evidence of established Christian and Muslim presence. The IAA accomplishes this by sometimes using bulldozers to erase some strata in order to get to what might have national significance for the present government. The use of archaeology as a means of dispossession and erasure of a people violates international law.
    </p>
    <br />
    <p>
      It is an irony of heightened order that the Museum of the Bible ignores Palestinian Christians who have maintained a Christian presence in the land where Jesus lived and where Christianity was born. One searches the Museum in vain for an exhibit showing the continuity of a Christian presence in the Holy Land. Christian communities of Bethlehem, Jerusalem, Beit Jala, Beit Sahour, Taybeh, Gaza, Ramallah, and other historic communities have ancestors who embraced the Christian faith in its earliest generations. Their presence in the Holy Land reaches back to the dawn of Christianity, yet the Museum ignores them.
    </p>
    <br />
    <p>
      A museum claiming to present the story of the Bible’s impact must ask why the voices of Palestinian Christians are absent when the story of the Bible in their homeland is presented. The Museum of the Bible should engage in a meaningful partnership with the Christians who still live that story.
    </p>
    <br />
    <p>
      The Museum of the Bible must seriously examine whether its current partnership with the IAA reflects the values it claims to represent. It must ask whether the process by which the Bible’s heritage is collected, interpreted, displayed, and promoted respects the dignity of all communities connected to it.
    </p>
    <br />
    <p>We therefore call upon the Museum of the Bible to:</p>
    <br />
    <ul>
      <li>End its institutional partnership with the Israel Antiquities Authority.</li>
      <li>Cease sponsoring, supporting, or participating in archaeological excavations and projects conducted in partnership with the Israel Antiquities Authority.</li>
      <li>End the exhibition of archaeological artifacts and long-term loans from the Israel Antiquities Authority.</li>
      <li>Return the Megiddo Church mosaic and support the restoration and preservation of the church it comes from.</li>
      <li>Commit to meaningful consultation and partnership with Palestinian Christian churches, Palestinian scholars, archaeologists, and heritage organizations connected to the history of the Holy Land.</li>
      <li>Publish transparent information regarding archaeological partnerships, artifact provenance, excavation involvement, and the communities affected by heritage projects presented by the museum.</li>
      <li>Ensure that future exhibitions concerning the Holy Land present the histories and voices of all communities connected to that heritage, including Palestinian Christians whose presence represents one of the oldest continuous Christian traditions in the world.</li>
    </ul>
